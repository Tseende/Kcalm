INSERT INTO foods (id, name_ru, name_en, kcal_100g, protein_100g, fat_100g, carbs_100g, source, external_id)
SELECT existing.id, ready.name_ru, ready.name_en, ready.kcal_100g, ready.protein_100g,
       ready.fat_100g, ready.carbs_100g, ready.source,
       CASE WHEN existing.id IS NULL THEN ready.external_id ELSE existing.external_id END
FROM ready
LEFT JOIN foods existing ON existing.id = (
    SELECT f.id
    FROM foods f
    WHERE f.source = 'seed' AND f.owner_user_id IS NULL AND f.deleted_at IS NULL
      AND f.name_ru = ready.name_ru
    ORDER BY f.id
    LIMIT 1
)
WHERE TRUE
ON CONFLICT(id) DO UPDATE SET
    name_en = excluded.name_en,
    kcal_100g = excluded.kcal_100g,
    protein_100g = excluded.protein_100g,
    fat_100g = excluded.fat_100g,
    carbs_100g = excluded.carbs_100g
WHERE foods.name_en IS NOT excluded.name_en OR foods.kcal_100g IS NOT excluded.kcal_100g
   OR foods.protein_100g IS NOT excluded.protein_100g OR foods.fat_100g IS NOT excluded.fat_100g
   OR foods.carbs_100g IS NOT excluded.carbs_100g;
