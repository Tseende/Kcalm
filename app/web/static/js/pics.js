export const FOOD_GROUPS = (() => {
  const used = new Set(GROUPS.flatMap(([, ks]) => ks));
  const rest = FOOD_ICONS.filter((k) => !used.has(k));
  return [...GROUPS.map(([t, ks]) => [t, ks.filter((k) => FOOD_ICONS.includes(k))]), ...(rest.length ? [['Другое', rest]] : [])];
})();

export function foodGroupOf(name, icon = null) {
  const k = FOOD_ICONS.includes(icon) ? icon : foodPicName(name);
  const g = FOOD_GROUPS.find(([, ks]) => ks.includes(k));
  return g ? g[0] : 'Другое';
}

export function foodPicName(name) {
  const t = String(name || '').toLowerCase().replace(/ё/g, 'е');
  for (const [file, re] of FOOD) if (re.test(t) || re.test(String(name || '').toLowerCase())) return file;
  return null;
}

function pic(path, size) {
  return h('span', { class: 'pic', 'aria-hidden': 'true', style: { width: size + 'px', height: size + 'px' } },
    h('img', { src: path, alt: '', loading: 'lazy', decoding: 'async', width: size, height: size }));
}

// null, если подходящей картинки нет: вызывающий код рисует обычную плитку.
export function foodPic(name, size = 40, icon = null) {
  const f = FOOD_ICONS.includes(icon) ? icon : foodPicName(name);
  return f ? pic(`img/food/${f}.webp?v=5`, size) : null;
}

