export function foodPicName(name) {
  const t = String(name || '').toLowerCase().replace(/ё/g, 'е');
  for (const [file, re] of FOOD) if (re.test(t) || re.test(String(name || '').toLowerCase())) return file;
  return null;
}

function pic(path, size) {
  return h('span', { class: 'pic', 'aria-hidden': 'true', style: { width: size + 'px', height: size + 'px' } },
    h('img', { src: path, alt: '', loading: 'lazy', decoding: 'async', width: size, height: size }));
}

// null, если подходящей картинки нет: вызывающий код рисует обычную плитку.
export function foodPic(name, size = 40) {
  const f = foodPicName(name);
  return f ? pic(`img/food/${f}.webp?v=1`, size) : null;
}

const DRINKS = new Set(['cola', 'cola_zero', 'fanta', 'tea', 'americano', 'cappuccino', 'flat_white', 'latte', 'juice', 'water', 'smoothie', 'beer', 'wine', 'energy', 'shake']);
const DRINK_ALIAS = { juice: 'juice_box' };

export function drinkPic(id, size = 48) {
  if (!DRINKS.has(id)) return null;
  return pic(`img/drink/${DRINK_ALIAS[id] || id}.webp?v=1`, size);
}
