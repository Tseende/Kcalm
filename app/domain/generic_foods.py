def generic_ref(name_ru: str, name_en: str = "") -> FoodRef | None:
    """Усреднённая запись по ключевым словам названия; None — категорию не угадали."""
    text = f"{name_ru} {name_en}".lower().replace("ё", "е")
    for keys, (kcal, protein, fat, carbs) in _RULES:
        if any(k.replace("ё", "е") in text for k in keys):
            return FoodRef(name_ru=name_ru, name_en=name_en or name_ru, kcal_100g=kcal,
                           protein_100g=protein, fat_100g=fat, carbs_100g=carbs,
                           source="seed", confidence=0.25)
    return None
