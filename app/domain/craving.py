"""Тяга к еде: распознавание фраз, безопасность, детерминированные выводы по данным.

Всё, что касается здоровья и цифр, считает код. LLM (если подключена) только
формулирует поддержку в диалоге и не может выдать число, которого нет в фактах.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

NIGHT_END = "05:00"           # ночное окно: от «кухня закрыта» до 05:00
EPISODE_WINDOW_MIN = 90       # столько после старта эпизода свободный текст идёт в поддержку

CATEGORIES = ("hunger", "emotion", "habit", "tired", "overate")

# Сильные фразы — реагируем в любое время; слабые — только в ночном окне.
_STRONG = re.compile(
    r"срываюсь|срывается|сорвал(?:ся|ась)|не могу остановиться|не могу перестать есть|"
    r"объел(?:ся|ась)|переел(?:а)?\b|жру\b|слопал(?:а)?|съел(?:а)? (?:всё|все) подряд|"
    r"съел(?:а)? весь холодильник|ночной жор|жор напал")
_WEAK = re.compile(
    r"хочу (?:есть|кушать|поесть|пожрать|жрать|сладк\w*|чего[- ]?нибудь|булочк\w*|шоколад\w*|"
    r"печень\w*|пицц\w*|чипс\w*|торт\w*|конфет\w*|мороженое\w*|перекусить)|"
    r"хочется (?:есть|кушать|поесть|сладк\w*|чего[- ]?нибудь|съесть|перекусить)|"
    r"тянет (?:на|к) \w+|голоден|голодна|голодный|голодная|жрать хочу|кушать хочу|"
    r"не могу уснуть.*(?:есть|холодильник)|тянет к холодильнику|иду к холодильнику")
# Фразы про уже съеденное — их надо записать как еду, а не вести разговор.
_LOG_VERBS = re.compile(r"\b(?:съел|съела|поел|поела|скушал|скушала|выпил|выпила|заказал|заказала)\b")

# Тревожные признаки: тут мы не «коучим диету», а мягко направляем к специалисту.
_PURGING = re.compile(
    r"вызва(?:л|ла|ть|ла бы)? рвоту|вызыва\w* рвоту|вырвал(?:а)? после еды|как вырвать|рвота после еды|слабительн\w*|мочегонн\w*|"
    r"наказал(?:а)? себя голодом|голодовк\w*|не буду есть (?:всю )?неделю")
_SELF_HARM = re.compile(
    r"хочу умереть|не хочу жить|навредить себе|причинить себе вред|убить себя|порезать себя|"
    r"режу себя")


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", text.lower().replace("ё", "е")).strip()


def is_night(local_time: str, cutoff: str) -> bool:
    """Ночное окно: после времени «кухня закрыта» и до 05:00 (через полночь)."""
    if cutoff <= local_time:
        return True
    return local_time < NIGHT_END


def detect_craving(text: str, local_time: str, cutoff: str) -> bool:
    """Это сообщение про тягу к еде, а не запись еды?"""
    t = _norm(text)
    if _STRONG.search(t):
        return True
    if _LOG_VERBS.search(t):
        return False
    return bool(_WEAK.search(t)) and is_night(local_time, cutoff)


def looks_like_food_log(text: str) -> bool:
    return bool(_LOG_VERBS.search(_norm(text)))


def risk_level(text: str) -> str:
    """'self_harm' | 'purging' | 'none'."""
    t = _norm(text)
    if _SELF_HARM.search(t):
        return "self_harm"
    if _PURGING.search(t):
        return "purging"
    return "none"


# ------------------------------------------------------------------ выводы по данным

@dataclass
class Facts:
    local_time: str
    kcal_so_far: int
    kcal_target: int
    protein_so_far: float
    protein_target: int
    meals_today: int
    hours_since_last_meal: float | None
    sleep_min: int | None
    water_ml: int
    water_goal_ml: int
    craving_count_7d: int
    overate_count_14d: int

    @property
    def kcal_left(self) -> int:
        return self.kcal_target - self.kcal_so_far


def insights(f: Facts) -> list[str]:
    """Наблюдения только из данных. Нет данных, значит нет и наблюдения."""
    out: list[str] = []
    evening = f.local_time >= "17:00" or f.local_time < NIGHT_END
    if f.meals_today == 0:
        out.append("В дневнике сегодня пусто: либо правда почти не ел(а), либо не записано. "
                   "Если не ел(а), это очень вероятный голод.")
    elif evening and f.kcal_target and f.kcal_so_far < 0.6 * f.kcal_target:
        out.append(f"Сегодня записано {f.kcal_so_far} из {f.kcal_target} ккал, заметно меньше плана. "
                   "Вечерняя тяга после лёгкого дня — частая реакция организма, скорее всего это "
                   "настоящий голод.")
    if evening and f.protein_target and f.meals_today and f.protein_so_far < 0.5 * f.protein_target:
        out.append(f"Белка набрано {f.protein_so_far:g} из {f.protein_target} г: при нехватке белка "
                   "голод возвращается быстрее.")
    if f.hours_since_last_meal is not None and f.hours_since_last_meal >= 4.5:
        out.append(f"С последнего приёма пищи прошло около {f.hours_since_last_meal:.0f} ч: "
                   "это уже нормальный промежуток для голода.")
    if f.sleep_min is not None and f.sleep_min < 360:
        out.append(f"Сон сегодня {f.sleep_min // 60} ч {f.sleep_min % 60:02d} мин: недосып усиливает "
                   "тягу к сладкому и жирному, а решимость слабее. Это физиология, не слабость.")
    if f.water_goal_ml and f.water_ml < 0.4 * f.water_goal_ml:
        out.append(f"Воды выпито {f.water_ml} из {f.water_goal_ml} мл: жажду легко принять за "
                   "голод, начни со стакана воды.")
    return out


def budget_line(f: Facts) -> str | None:
    if not f.kcal_target or not f.meals_today:
        return None
    left = f.kcal_left
    if left >= 150:
        return f"До плана на день осталось {left} ккал: небольшой осознанный перекус вполне вписывается."
    return (f"Дневной план уже почти выбран ({f.kcal_so_far} из {f.kcal_target} ккал). "
            "Но настоящий голод ночью не повод терпеть до утра: небольшой перекус на 100–200 ккал "
            "не ломает прогресс, он считается по неделе, а не по одному вечеру.")


def prevention_tips(f: Facts, category: str) -> list[str]:
    """Что сделать завтра, чтобы вечером было спокойнее. Только из данных и категории."""
    tips: list[str] = []
    if f.meals_today and f.kcal_target and f.kcal_so_far < 0.6 * f.kcal_target:
        tips.append("Завтра подвинь часть калорий на обед и полдник и добавь белок (творог, яйца, "
                    "курица, рыба): сытый день часто означает спокойный вечер.")
    if f.sleep_min is not None and f.sleep_min < 360:
        tips.append("Постарайся лечь пораньше: недосып — один из главных триггеров вечерней тяги.")
    if category in ("emotion", "habit"):
        tips.append("Придумай заранее «замену»: чай, душ, короткая прогулка или звонок другу, "
                    "и держи её под рукой на вечер.")
    if f.craving_count_7d >= 3:
        tips.append("Такое повторяется на неделе: закрепи ритуал «кухня закрыта» (чистка зубов и "
                    "чай после ужина) и заведи план ужина на 30 г белка.")
    if not tips:
        tips.append("Завтра обычный план: завтрак с белком, воды в течение дня и ужин без спешки.")
    return tips[:3]


# --------------------------------------------------------------------- безопасность

BANNED_PHRASES = (
    "слабоволи", "слабак", "отработай", "отработать", "сожги", "сжечь", "пропусти завтрак",
    "пропусти ужин", "пропусти обед", "поголодай", "ничего не ешь", "разгрузочн", "детокс",
    "компенсируй", "накажи себя", "заслужил",
)


def violates_policy(text: str) -> bool:
    """Ответ модели нарушает правила: стыд, компенсация, голодание."""
    t = _norm(text)
    return any(p in t for p in BANNED_PHRASES)


