"""Build the catalogue sprite from the existing food thumbnails."""
import json
from pathlib import Path

from PIL import Image

STATIC = Path(__file__).resolve().parents[1] / "app" / "web" / "static"
CELL = 56
COLUMNS = 16


def main() -> None:
    files = sorted((STATIC / "img" / "food").glob("*.webp"))
    if not files:
        raise SystemExit("No food thumbnails found")
    rows = (len(files) + COLUMNS - 1) // COLUMNS
    atlas = Image.new("RGBA", (COLUMNS * CELL, rows * CELL))
    for i, path in enumerate(files):
        with Image.open(path) as source:
            image = source.convert("RGBA")
        image.thumbnail((CELL, CELL), Image.Resampling.LANCZOS)
        x = (i % COLUMNS) * CELL + (CELL - image.width) // 2
        y = (i // COLUMNS) * CELL + (CELL - image.height) // 2
        atlas.paste(image, (x, y))
    atlas.save(STATIC / "img" / "food-atlas.webp", quality=82, method=6)

    names = [json.dumps(p.stem, ensure_ascii=False) for p in files]
    chunks = [", ".join(names[i:i + 8]) for i in range(0, len(names), 8)]
    keys = ",\n  ".join(chunks)
    (STATIC / "js" / "food_atlas.js").write_text(
        f"// Generated by tools/build_food_atlas.py.\n"
        f"export const COLUMNS = {COLUMNS};\nexport const ROWS = {rows};\n"
        f"export const KEYS = [\n  {keys},\n];\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
