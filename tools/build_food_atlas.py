"""Build lazily loaded catalogue sprite tiles from the existing food thumbnails."""
import json
from pathlib import Path

from PIL import Image

STATIC = Path(__file__).resolve().parents[1] / "app" / "web" / "static"
CELL = 56
COLUMNS = 8
TILES = 4


def make_tile(files: list[Path], number: int) -> dict:
    rows = (len(files) + COLUMNS - 1) // COLUMNS
    atlas = Image.new("RGBA", (COLUMNS * CELL, rows * CELL))
    for i, path in enumerate(files):
        with Image.open(path) as source:
            image = source.convert("RGBA")
        image.thumbnail((CELL, CELL), Image.Resampling.LANCZOS)
        x = (i % COLUMNS) * CELL + (CELL - image.width) // 2
        y = (i // COLUMNS) * CELL + (CELL - image.height) // 2
        atlas.paste(image, (x, y))
    asset = f"img/food-atlas-{number}.webp"
    atlas.save(STATIC / asset, quality=82, method=6)
    return {"asset": asset, "rows": rows, "keys": [p.stem for p in files]}


def main() -> None:
    files = sorted((STATIC / "img" / "food").glob("*.webp"))
    if not files:
        raise SystemExit("No food thumbnails found")
    batch_size = (len(files) + TILES - 1) // TILES
    tiles = [make_tile(files[i:i + batch_size], number)
             for number, i in enumerate(range(0, len(files), batch_size), start=1)]
    manifest = ",\n  ".join(json.dumps(tile, ensure_ascii=False) for tile in tiles)
    (STATIC / "js" / "food_atlas.js").write_text(
        f"// Generated by tools/build_food_atlas.py.\n"
        f"export const COLUMNS = {COLUMNS};\n"
        f"export const TILES = [\n  {manifest},\n];\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
