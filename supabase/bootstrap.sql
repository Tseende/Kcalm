-- Fresh installation of the bot schema (SQLite schema version 41).

-- Food-image bytes are intentionally excluded; meal_photos contains metadata only.

-- Run as the schema owner in the Supabase SQL Editor or through psql.

BEGIN;

CREATE SCHEMA bot;

REVOKE ALL ON SCHEMA bot FROM PUBLIC, anon, authenticated, service_role;

SET LOCAL search_path = bot, pg_catalog;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tg_id BIGINT NOT NULL UNIQUE,
    sex TEXT NOT NULL DEFAULT 'male' CHECK (sex IN ('male','female')),
    birth_date DATE,
    height_cm DOUBLE PRECISION,
    start_weight_kg DOUBLE PRECISION,
    tz TEXT NOT NULL DEFAULT 'Europe/Minsk',
    eating_cutoff TIME NOT NULL DEFAULT '21:00',
    activity_pa DOUBLE PRECISION NOT NULL DEFAULT 1.12,
    goal_weight_kg DOUBLE PRECISION,
    target_rate_kg_week DOUBLE PRECISION NOT NULL DEFAULT -0.5,
    onboarded INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
, care_mode INTEGER NOT NULL DEFAULT 0, ref_code TEXT, invited_by BIGINT REFERENCES users(id) ON DELETE SET NULL, invites_left INTEGER NOT NULL DEFAULT 3, streak_freezes INTEGER NOT NULL DEFAULT 0, onboarding_skipped INTEGER NOT NULL DEFAULT 0 CHECK (onboarding_skipped IN (0, 1)));

CREATE TABLE foods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_ru TEXT NOT NULL,
    name_en TEXT NOT NULL,
    kcal_100g DOUBLE PRECISION NOT NULL,
    protein_100g DOUBLE PRECISION NOT NULL,
    fat_100g DOUBLE PRECISION NOT NULL,
    carbs_100g DOUBLE PRECISION NOT NULL,
    source TEXT NOT NULL CHECK (source IN ('off','usda','user','seed','llm','green')),
    barcode TEXT,
    external_id TEXT, owner_user_id BIGINT REFERENCES users(id) ON DELETE CASCADE, default_grams DOUBLE PRECISION, unit_name TEXT, unit_grams DOUBLE PRECISION, brand TEXT, deleted_at TIMESTAMPTZ, created_at TIMESTAMPTZ, icon TEXT, nutrition_source TEXT CHECK (nutrition_source IN ('label', 'off')),
    UNIQUE(source, external_id)
);

CREATE TABLE llm_calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    purpose TEXT NOT NULL,
    model TEXT NOT NULL,
    tokens_in INTEGER, tokens_out INTEGER,
    cost_usd DOUBLE PRECISION,
    latency_ms INTEGER,
    ok INTEGER NOT NULL,
    error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
, tokens_cached INTEGER);

CREATE TABLE model_usage_daily (
    day DATE NOT NULL,
    user_id BIGINT NOT NULL,
    model TEXT NOT NULL,
    requests INTEGER NOT NULL DEFAULT 0,
    input_tokens INTEGER NOT NULL DEFAULT 0,
    output_tokens INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (day, user_id, model)
);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    entity_type TEXT NOT NULL,
    entity_id BIGINT NOT NULL,
    event_type TEXT NOT NULL,
    before_json JSONB,
    after_json JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recent_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    file_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE chat_messages(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    role TEXT NOT NULL,
    text TEXT NOT NULL,
    meal_id BIGINT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE chat_topics (
    chat_id BIGINT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('diary', 'support')),
    thread_id BIGINT NOT NULL, name TEXT NOT NULL DEFAULT '', welcome_version INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (chat_id, kind),
    UNIQUE (chat_id, thread_id)
);

CREATE TABLE food_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    food_id BIGINT NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    alias_text TEXT NOT NULL,
    UNIQUE(user_id, alias_text)
);

CREATE TABLE user_foods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    food_id BIGINT NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    default_grams DOUBLE PRECISION,
    times_used INTEGER NOT NULL DEFAULT 0,
    last_used_at TIMESTAMPTZ
);

CREATE TABLE meals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    eaten_at_utc TIMESTAMPTZ NOT NULL,
    local_date DATE NOT NULL,
    local_time TIME NOT NULL,
    meal_type TEXT NOT NULL CHECK (meal_type IN ('breakfast','lunch','dinner','snack')),
    source TEXT NOT NULL CHECK (source IN ('photo','voice','text','combo','manual')),
    photo_path TEXT,
    transcript TEXT,
    kcal_total INTEGER NOT NULL DEFAULT 0,
    protein_g DOUBLE PRECISION NOT NULL DEFAULT 0,
    fat_g DOUBLE PRECISION NOT NULL DEFAULT 0,
    carbs_g DOUBLE PRECISION NOT NULL DEFAULT 0,
    kcal_low INTEGER NOT NULL DEFAULT 0,
    kcal_high INTEGER NOT NULL DEFAULT 0,
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    method TEXT NOT NULL DEFAULT 'db' CHECK (method IN ('db','mixed','llm_prior')),
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE targets_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    valid_from DATE NOT NULL,
    kcal_target INTEGER NOT NULL,
    protein_g DOUBLE PRECISION, fat_g DOUBLE PRECISION, carbs_g DOUBLE PRECISION,
    tdee_est INTEGER,
    reason TEXT NOT NULL
);

CREATE TABLE raw_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    file_path TEXT,
    file_hash TEXT,
    parsed_json JSONB,
    model TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE insights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    payload_json JSONB NOT NULL,
    shown_at TIMESTAMPTZ
);

CREATE TABLE pending_inputs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    payload_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
, message_thread_id BIGINT NOT NULL DEFAULT 0);

CREATE TABLE reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    local_time TIME NOT NULL,
    enabled INTEGER NOT NULL DEFAULT 1,
    last_sent_at TIMESTAMPTZ, days TEXT,
    UNIQUE(user_id, kind)
);

CREATE TABLE craving_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    started_utc TIMESTAMPTZ NOT NULL,
    local_date DATE NOT NULL,
    local_time TIME NOT NULL,
    trigger_text TEXT,
    category TEXT NOT NULL DEFAULT 'unknown'
        CHECK (category IN ('unknown','hunger','emotion','habit','tired','overate')),
    outcome TEXT NOT NULL DEFAULT 'open'
        CHECK (outcome IN ('open','resisted','ate_planned','overate','dismissed')),
    kcal_so_far INTEGER,
    kcal_target INTEGER,
    risk_flag INTEGER NOT NULL DEFAULT 0,
    followup_at_utc TIMESTAMPTZ,
    followup_sent INTEGER NOT NULL DEFAULT 0,
    closed_utc TIMESTAMPTZ
, lesson TEXT, summary TEXT, mode TEXT NOT NULL DEFAULT 'craving');

CREATE TABLE if_then_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    if_text TEXT NOT NULL,
    then_text TEXT NOT NULL,
    category TEXT CHECK (category IS NULL OR category IN ('hunger','emotion','habit','tired','overate')),
    remind_time TIME,
    last_sent_date DATE,
    created_utc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE weekly_goals(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    week_start DATE NOT NULL,
    kind TEXT NOT NULL,
    target_days INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, week_start));

CREATE TABLE user_reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    template TEXT NOT NULL DEFAULT 'custom',
    title TEXT NOT NULL,
    text TEXT,
    local_time TIME NOT NULL,
    days TEXT,
    every_min INTEGER,
    until_time TIME,
    enabled INTEGER NOT NULL DEFAULT 1,
    last_sent_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE widget_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    local_date DATE NOT NULL,
    chat_id BIGINT NOT NULL,
    message_id BIGINT NOT NULL,
    ref_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE access_grants (
    tg_id BIGINT PRIMARY KEY,
    inviter_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE referrals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inviter_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    invitee_tg_id BIGINT NOT NULL UNIQUE,
    invitee_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    invitee_name TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    onboarded_at TIMESTAMPTZ,
    activated_at TIMESTAMPTZ,
    rewarded_at TIMESTAMPTZ
, friend_bonus_days INTEGER NOT NULL DEFAULT 0 CHECK(friend_bonus_days >= 0), inviter_bonus_days INTEGER NOT NULL DEFAULT 0 CHECK(inviter_bonus_days >= 0));

CREATE TABLE streak_freeze_days (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    local_date DATE NOT NULL,
    PRIMARY KEY (user_id, local_date)
);

CREATE TABLE "dishes" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('plate','deep_plate','bowl','salad_bowl','mug','cup','glass','pan','pot','container','jar','thermos','dessert_plate','square_plate','oval_plate','rectangular_plate','pasta_plate','divided_plate','platter','ramekin','other')),
    diameter_cm DOUBLE PRECISION,
    depth_cm DOUBLE PRECISION,
    volume_ml DOUBLE PRECISION,
    photo_path TEXT,
    is_default INTEGER NOT NULL DEFAULT 0,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
, width_cm DOUBLE PRECISION);

CREATE TABLE meal_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_id BIGINT NOT NULL REFERENCES meals(id) ON DELETE CASCADE,
    name_ru TEXT NOT NULL,
    name_en TEXT NOT NULL,
    grams DOUBLE PRECISION NOT NULL,
    kcal INTEGER NOT NULL,
    protein_g DOUBLE PRECISION NOT NULL DEFAULT 0,
    fat_g DOUBLE PRECISION NOT NULL DEFAULT 0,
    carbs_g DOUBLE PRECISION NOT NULL DEFAULT 0,
    food_ref_id BIGINT REFERENCES foods(id) ON DELETE SET NULL,
    source TEXT NOT NULL DEFAULT 'seed',
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    edited_by_user INTEGER NOT NULL DEFAULT 0,
    snapshot_json JSONB
, kcal_100g DOUBLE PRECISION, protein_100g DOUBLE PRECISION, fat_100g DOUBLE PRECISION, carbs_100g DOUBLE PRECISION);

CREATE TABLE activity_daily (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    local_date DATE NOT NULL,
    steps INTEGER, distance_km DOUBLE PRECISION, active_kcal INTEGER,
    resting_hr INTEGER, avg_hr INTEGER, active_minutes INTEGER,
    workouts_json JSONB,
    source TEXT NOT NULL,
    raw_observation_id BIGINT REFERENCES raw_observations(id) ON DELETE SET NULL,
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    UNIQUE(user_id, local_date, source)
);

CREATE TABLE sleep_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    wake_date DATE NOT NULL,
    sleep_start_utc TIMESTAMPTZ, sleep_end_utc TIMESTAMPTZ,
    duration_min INTEGER, deep_min INTEGER, light_min INTEGER,
    rem_min INTEGER, awake_min INTEGER, score INTEGER,
    source TEXT NOT NULL,
    raw_observation_id BIGINT REFERENCES raw_observations(id) ON DELETE SET NULL,
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    UNIQUE(user_id, wake_date, source)
);

CREATE TABLE photo_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status TEXT NOT NULL CHECK (status IN ('awaiting_caption','ready')),
    context_json JSONB NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
, meal_id BIGINT REFERENCES meals(id) ON DELETE SET NULL, message_thread_id BIGINT NOT NULL DEFAULT 0);

CREATE TABLE "body_measurements" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    measured_at_utc TIMESTAMPTZ,
    local_date DATE NOT NULL,
    weight_kg DOUBLE PRECISION, bmi DOUBLE PRECISION, body_fat_pct DOUBLE PRECISION, fat_mass_kg DOUBLE PRECISION,
    muscle_mass_kg DOUBLE PRECISION, skeletal_muscle_pct DOUBLE PRECISION, body_water_pct DOUBLE PRECISION,
    bone_mass_kg DOUBLE PRECISION, protein_pct DOUBLE PRECISION, visceral_fat INTEGER,
    bmr_kcal INTEGER, metabolic_age INTEGER,
    fasting INTEGER,
    skeletal_muscle_kg DOUBLE PRECISION,
    subcutaneous_fat_pct DOUBLE PRECISION,
    impedance_ohm DOUBLE PRECISION,
    source TEXT NOT NULL CHECK (source IN ('screenshot','csv','manual','picooc_api')),
    raw_observation_id BIGINT REFERENCES raw_observations(id) ON DELETE SET NULL,
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.5, muscle_mass_pct DOUBLE PRECISION, body_tone DOUBLE PRECISION, body_score DOUBLE PRECISION, resting_hr INTEGER,
    UNIQUE(user_id, local_date, source, weight_kg)
);

CREATE TABLE water_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    logged_at_utc TIMESTAMPTZ NOT NULL,
    local_date DATE NOT NULL,
    local_time TIME NOT NULL,
    ml INTEGER NOT NULL CHECK (ml BETWEEN 10 AND 3000),
    source TEXT NOT NULL CHECK (source IN ('text','voice','command')),
    raw_text TEXT
, meal_id BIGINT REFERENCES meals(id) ON DELETE CASCADE);

CREATE TABLE craving_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES craving_events(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('user','assistant')),
    text TEXT NOT NULL,
    created_utc TIMESTAMPTZ NOT NULL
);

CREATE TABLE meal_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_id BIGINT NOT NULL REFERENCES meals(id) ON DELETE CASCADE,
    path TEXT NOT NULL,
    dish_id BIGINT,
    position INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE favorite_meals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    meal_id BIGINT NOT NULL REFERENCES meals(id),
    sig        TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, title TEXT, note TEXT, use_count INTEGER NOT NULL DEFAULT 0, last_used_at TIMESTAMPTZ, category TEXT,
    UNIQUE (user_id, sig)
);

CREATE TABLE reward_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    amount INTEGER NOT NULL,
    reason TEXT NOT NULL,
    referral_id BIGINT REFERENCES referrals(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE meal_telegram_albums (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    media_group_id TEXT NOT NULL,
    meal_id BIGINT NOT NULL REFERENCES meals(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, media_group_id)
);

CREATE TABLE meal_edits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_item_id BIGINT NOT NULL REFERENCES meal_items(id) ON DELETE CASCADE,
    field TEXT NOT NULL,
    old_value TEXT,
    new_value TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE food_barcodes (
    food_id BIGINT NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    gtin TEXT NOT NULL CHECK (gtin ~ '^[0-9]{14}$'),
    PRIMARY KEY (food_id, gtin)
);

CREATE INDEX idx_food_barcodes_gtin ON food_barcodes(gtin);

CREATE INDEX idx_foods_name_en ON foods(name_en);

CREATE INDEX idx_foods_name_ru ON foods(name_ru);

CREATE INDEX idx_meals_user_date ON meals(user_id, local_date);

CREATE INDEX idx_raw_hash ON raw_observations(file_hash);

CREATE INDEX idx_recent_hash ON recent_files(user_id, file_hash, created_at);

CREATE INDEX idx_body_user_date ON body_measurements(user_id, local_date);

CREATE INDEX idx_water_user_date ON water_log(user_id, local_date);

CREATE INDEX idx_craving_user_date ON craving_events(user_id, local_date);

CREATE INDEX idx_craving_msg_event ON craving_messages(event_id);

CREATE INDEX idx_rules_user ON if_then_rules(user_id);

CREATE INDEX idx_water_meal ON water_log(meal_id);

CREATE INDEX idx_meal_photos_meal ON meal_photos(meal_id);

CREATE INDEX idx_foods_owner ON foods(owner_user_id);

CREATE INDEX idx_chat_messages_user ON chat_messages(user_id, id);

CREATE INDEX idx_meal_items_meal ON meal_items(meal_id);

CREATE INDEX idx_foods_barcode ON foods(barcode);

CREATE INDEX idx_favorite_meals_user ON favorite_meals(user_id);

CREATE INDEX idx_user_reminders_user ON user_reminders(user_id);

CREATE UNIQUE INDEX ux_widget_chat_message ON widget_messages(chat_id, message_id);

CREATE INDEX idx_widget_user_kind_date ON widget_messages(user_id, kind, local_date);

CREATE UNIQUE INDEX idx_users_ref_code ON users(ref_code);

CREATE INDEX idx_referrals_inviter ON referrals(inviter_user_id);

CREATE INDEX idx_referrals_invitee_user ON referrals(invitee_user_id);

CREATE INDEX idx_reward_log_user ON reward_log(user_id);

CREATE INDEX idx_dishes_user ON dishes(user_id);

CREATE INDEX idx_meal_telegram_albums_meal ON meal_telegram_albums(meal_id);

CREATE UNIQUE INDEX idx_subscription_day_award ON reward_log(referral_id, reason)
    WHERE kind = 'subscription_days' AND referral_id IS NOT NULL;

REVOKE ALL ON ALL TABLES IN SCHEMA bot FROM PUBLIC, anon, authenticated, service_role;

REVOKE ALL ON ALL SEQUENCES IN SCHEMA bot FROM PUBLIC, anon, authenticated, service_role;

COMMIT;
