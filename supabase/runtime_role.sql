-- Run as project owner. Set the login password securely before enabling LOGIN.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kcalm_app') THEN
    CREATE ROLE kcalm_app NOLOGIN;
  END IF;
END
$$;
GRANT USAGE ON SCHEMA bot TO kcalm_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA bot TO kcalm_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA bot TO kcalm_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA bot
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO kcalm_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA bot
  GRANT USAGE, SELECT ON SEQUENCES TO kcalm_app;
